import assert from 'node:assert/strict';
import {buildChatPrompt,buildWorkPrompt} from '../dsh-chatgpt-plugin/chat-ui-prompt.js';
const old=[];
for(let i=0;i<30;i++)old.push({role:'user',content:'old-'+i+'x'.repeat(5000)},{role:'assistant',content:'old-answer-'+i+'y'.repeat(5000)});
const tools=[{name:'ping',description:'test',parameters:{type:'object',properties:{}}}];
const options={system:'PERSONA_KEEP',messages:[{role:'system',content:'MEMORY_KEEP'},...old,{role:'user',content:'CURRENT_KEEP'},{role:'user',content:'CURRENT_MEMORY_KEEP'}],tools};
const result=await buildChatPrompt(options);
assert.ok(result.prompt.length<=100000);
const body=JSON.parse(result.prompt.slice(result.prompt.indexOf('\n{')+1));
assert.deepEqual(body.system,['PERSONA_KEEP','MEMORY_KEEP']);
assert.deepEqual(body.tools,tools);
assert.equal(body.history.at(-1).content[0].text,'CURRENT_MEMORY_KEEP');
assert.equal(body.history.at(-2).content[0].text,'CURRENT_KEEP');
assert.ok(body.contextWindow.omittedMessages>0);
assert.equal(body.contextWindow.persistedHistoryUnchanged,true);
assert.equal(body.history[0].role,'user');
const call={type:'tool-call',id:'test-call',name:'ping',arguments:'{}'};
const pending=await buildChatPrompt({...options,messages:[...options.messages,{role:'assistant',content:[call]},{role:'tool',source:{callId:'test-call'},content:'pong'}]});
const pendingBody=JSON.parse(pending.prompt.slice(pending.prompt.indexOf('\n{')+1));
assert.equal(pendingBody.history.at(-2).content[0].id,'test-call');
assert.equal(pendingBody.history.at(-1).callId,'test-call');
assert.ok(pendingBody.history.some(m=>m.content.some(b=>b.text==='CURRENT_KEEP')));
await assert.rejects(buildChatPrompt({system:'z'.repeat(150001),messages:[{role:'user',content:'current'}]}),/CHAT_UI_CONTEXT_TOO_LARGE/);
await assert.rejects(buildChatPrompt({messages:[{role:'user',content:'z'.repeat(150001)}]}),/CHAT_UI_CONTEXT_TOO_LARGE/);
const short=await buildChatPrompt({messages:[{role:'user',content:'short'}]});
const shortBody=JSON.parse(short.prompt.slice(short.prompt.indexOf('\n{')+1));
assert.equal(shortBody.history.length,1);
assert.equal(shortBody.contextWindow.omittedMessages,0);
const work=await buildWorkPrompt({system:'PRIVATE_PERSONA',tools:[{name:'private_tool'}],messages:[{role:'user',content:'old task'},{role:'assistant',content:'old answer'},{role:'user',content:'current work task\nFile: C:\\Users\\me\\.dsh-qqbot\\media\\report.pdf'}]},null);
assert.ok(work.prompt.includes('current work task'));
assert.ok(!work.prompt.includes('PRIVATE_PERSONA'));
assert.ok(!work.prompt.includes('old task'));
assert.ok(!work.prompt.includes('report.pdf'));
assert.equal(work.files.length,0);
const workImage=await buildWorkPrompt({system:'PRIVATE_PERSONA',messages:[{role:'user',content:[{type:'text',text:'describe this image'},{type:'image',attachment:'qq-image'}]}]},
  {readImageRequest:async attachment=>{assert.equal(attachment,'qq-image');return{mediaType:'image/jpeg',data:Buffer.from('image fixture')};}});
assert.equal(workImage.files[0].type,'image/jpeg');
assert.equal(workImage.files[0].name,'qq-image-1.jpg');
assert.ok(!workImage.prompt.includes('PRIVATE_PERSONA'));
let imageReads=0;
const imageResult=await buildChatPrompt({messages:[{role:'user',content:[{type:'image',attachment:'old-image'},{type:'text',text:'x'.repeat(150000)}]},{role:'assistant',content:'old answer'},{role:'user',content:[{type:'text',text:'current image'},{type:'image',attachment:'new-image'}]}]},
  {readImageRequest:async attachment=>{assert.equal(attachment,'new-image');imageReads++;return{mediaType:'image/png',data:Buffer.from('fixture')};}});
assert.equal(imageReads,1);assert.equal(imageResult.images.length,1);
assert.equal(imageResult.prompt.includes('current image'),true);
