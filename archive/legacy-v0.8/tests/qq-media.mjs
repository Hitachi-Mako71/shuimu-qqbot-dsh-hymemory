const identity={appId:'fixture-app',scope:'group',peerId:'fixture-room'};
const attachment={content_type:'image/png',filename:'original.png',url:'https://example.invalid/owned-attachment'};
const state={},ctx={message:{kind:'group',groupOpenid:identity.peerId,senderId:'member',messageId:'original-id',msgIdx:'original-ref',attachments:[attachment]},state};
