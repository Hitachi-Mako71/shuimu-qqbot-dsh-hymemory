import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'yuzu-qq-media-'));
process.env.QQBOT_MEDIA_DIR=path.join(root,'cache');
const media=await import('../dsh-hymemory-plugin/qq-media.js');
const owned=path.join(root,'downloads');fs.mkdirSync(owned);
