import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'yuzu-fiction-continuity-'));
process.env.QQBOT_COMPANION_DIR=path.join(root,'data','companion');
fs.mkdirSync(process.env.QQBOT_COMPANION_DIR,{recursive:true});
fs.copyFileSync(new URL('../fiction-canon.json',import.meta.url),path.join(root,'fiction-canon.json'));
globalThis.fetch=async()=>{throw Error('offline-fixture');};
const ledger=await import('../dsh-hymemory-plugin/fiction-ledger.js');
const ui=await import('../dsh-hymemory-plugin/fiction-ui.js');
const engine=await import('../dsh-hymemory-plugin/fiction-engine.js');
const key='qq-'+'a'.repeat(64),other='qq-'+'b'.repeat(64);
let world=ledger.loadWorld(key);
const detail='我在书房翻开虚构小书《灯下的鲸》，读到一句原创的话：“慢慢走，也会遇见花开。”我把它抄在蓝色书签上。';
const draft={summary:'书房读书并制作书签。',facts:[],threads:[],followups:[{question:'什么书？',answer:'《灯下的鲸》',evidence:'虚构小书《灯下的鲸》'},{question:'什么句子？',answer:'慢慢走，也会遇见花开。',evidence:'“慢慢走，也会遇见花开。”'}]};
const episode={id:'fixture-event',date:'2026-10-23',time:'13:00',kind:'fiction',channel:'life',detail,message:'今天在书房翻旧书，读到一句很妙的话。',followups:draft.followups};
ledger.commitEpisode(key,world,episode,draft,{kind:'fixture',verdict:'accepted'});
let checks=0;const check=(value,message)=>{assert.ok(value,message);checks++;};
check(ledger.activeRecords(world).some(r=>r.content.includes('慢慢走，也会遇见花开')),'episodic index must retain the exact quote, not just the lossy summary');
check(ui.fictionQuestion('是什么书什么句子',world),'elliptical followup must use the fiction ledger');
check(ui.dailyInvitation('你今天有什么有趣的事？'));
check(!ui.dailyInvitation('我今天有个有趣的事告诉你'));
const context=await ui.fictionContext(key,'是什么书什么句子');
check(context.includes('灯下的鲸')&&context.includes('慢慢走，也会遇见花开'));
check(!(await ui.fictionContext(other,'是什么书什么句子')).includes('灯下的鲸'),'another QQ scope cannot recall this event');
// Existing immutable Hy records gain a new evidence revision; the old record is preserved.
const event=Object.values(world.events)[0],oldId=event.recordId;
delete event.evidenceVersion;event.recordId=event.eventId;world.records[event.eventId]={id:event.eventId,content:'旧摘要',meta:{fiction:true,type:'episodic'}};
ledger.saveWorld(key,world);world=ledger.loadWorld(key);
check(Object.values(world.events)[0].recordId!==event.eventId && world.records[event.eventId].content==='旧摘要');
check(ledger.activeRecords(world).some(r=>r.content.includes('慢慢走，也会遇见花开')));
check(world.pendingIndex.includes(Object.values(world.events)[0].recordId));
check(typeof engine.validateNarrative==='function');
assert.throws(()=>engine.validateNarrative({detail:'随便翻书，没记下句子。',message:'读到一句很妙的话',followups:[]}),/Book|Quote/);checks++;
engine.validateNarrative({...draft,detail,message:episode.message});checks++;
assert.throws(()=>engine.validateNarrative({...draft,detail,message:episode.message,followups:[{question:'猫叫什么',answer:'没有证据的名字',evidence:'虚构小书《灯下的鲸》'}]}),/Followup/);checks++;
world=ledger.loadWorld(key);
const capture=[];
const reply=await engine.answerFiction(key,async(system,input)=>{capture.push(JSON.parse(input));return capture.length===1?'虚构小书是《灯下的鲸》，原句是“慢慢走，也会遇见花开。”。':JSON.stringify({valid:true,reasons:[]});},'你读书后做了什么？');
check(reply.includes('灯下的鲸')&&JSON.stringify(capture[0]).includes('慢慢走，也会遇见花开'));
const direct=await engine.answerFiction(key,async()=>{throw Error('known followup must not call a model');},'是什么书、哪句话？');
check(direct.includes('灯下的鲸')&&direct.includes('慢慢走，也会遇见花开'));
console.log(JSON.stringify({checks,passed:true,realModelCalls:0,realQQSends:0}));
